// Arithmetic

let a = 12;
let b = 4;

console.log(a + b);
console.log(a - b);
console.log(a * b);
console.log(a / b);
console.log(a % b);
console.log(a ** b);

// Assignment

let x = 20;

x += 10;
x -= 5;
x *= 2;
x /= 5;

console.log(x);

// Comparison

console.log(15 > 10);
console.log(15 < 10);
console.log(15 >= 15);
console.log(15 === 15);
console.log(15 !== 10);

// Logical

let age = 20;
let hasID = false;

console.log(age >= 18 && hasID);
console.log(age < 18 || hasID);
console.log(!hasID);

// Ternary

let status = age >= 18 ? "Adult" : "Minor";
console.log(status);
